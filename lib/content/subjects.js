export const SUBJECT_MAP = Object.fromEntries(SUBJECTS.map((s) => [s.id, s]));

export function getSubject(id) {
  return SUBJECT_MAP[id] || null;
}

export function subjectAvailableForGrade(subject, grade) {
  if (!grade) return true;
  return grade >= subject.grades[0] && grade <= subject.grades[1];
}
